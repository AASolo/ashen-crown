/** Номер шага, когда пролог пройден: дальше бесконечные Разломы. */
export const QUEST_DONE = STEPS.length;

export const questStep = (d: HeroData) => d.quest ?? QUEST_DONE;
export const inPrologue = (d: HeroData) => questStep(d) < QUEST_DONE;

export function goalText(d: HeroData): string {
  const s = STEPS[questStep(d)];
  if (!s) return '';
  return s.goal.replace('{n}', String(d.qProg ?? 0)).replace('{need}', String(s.need ?? 0));
}

